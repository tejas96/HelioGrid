const map = <K extends string>(keys: readonly K[], word: (key: K) => TranslatedText) =>
  Object.fromEntries(keys.map((key) => [key, word(key)])) as Record<K, TranslatedText>;

/**
 * Every fixed word of the import wizard, and the sentences built from its facts. The row words —
 * a question, a report reason, what a fix set — are `catalogImportRowWords`.
 */
export function catalogImportWordsBase(t: T) {
  const steps = [t(WORDS.file), t(WORDS.columns), t(WORDS.preview), t(WORDS.report)] as const;
  const stepName = (step: number) => steps[step] ?? steps[0];
  return {
    title: t(WORDS.title),
    close: t(WORDS.close),
    back: t(WORDS.back),
    steps,
    stepsLabel: t(WORDS.stepsLabel),
    location: (step: number) => t(WORDS.location, { step: step + 1, name: stepName(step) }),
    locationLabel: (step: number) =>
      t(WORDS.locationLabel, { step: step + 1, name: stepName(step) }),
    whereYouAre: t(WORDS.whereYouAre),
    reportAfterRun: t(WORDS.reportAfterRun),
    choose: t(WORDS.choose),
    chooseHint: (size: number) => t(WORDS.chooseHint, { size }),
    dropAnother: t(WORDS.dropAnother),
    dropAnotherHint: (size: number) => t(WORDS.dropAnotherHint, { size }),
    replace: t(WORDS.replace),
    fileMeta: (rows: number, columns: number) => t(WORDS.fileMeta, { rows, columns }),
    fileProblem: t(WORDS.fileProblem),
    subtitle: (file: string, rows: number) => t(WORDS.subtitle, { file, rows }),
    subtitleImported: (file: string, rows: number, date: string, time: string) =>
      t(WORDS.subtitleImported, { file, rows, date, time }),
    stamp: (date: string, time: string) => t(WORDS.stamp, { date, time }),
    sheetLabel: t(WORDS.sheetLabel),
    sheetHelper: (count: number) => t(WORDS.sheetHelper, { count }),
    headerRowLabel: t(WORDS.headerRowLabel),
    rowOption: (row: number) => t(WORDS.rowOption, { row }),
    rowReads: (row: number) => t(WORDS.rowReads, { row }),
    rowOfFile: (row: number) => t(WORDS.rowOfFile, { row }),
    untouched: t(WORDS.untouched),
    keptReports: t(WORDS.keptReports),
    saved: (date: string) => t(WORDS.saved, { date }),
    showMore: t(WORDS.showMore),
    tryAgain: t(WORDS.tryAgain),
    unreadableTitle: t(WORDS.unreadableTitle),
    unreadableMessage: t(WORDS.unreadableMessage),
    matchedIntro: (matched: number, columns: number, open: number) =>
      open === 0
        ? t(WORDS.matchedAll, { columns })
        : t(WORDS.matchedIntro, { matched, columns, open }),
    matchedAutomatically: t(WORDS.matchedAutomatically),
    chooseField: t(WORDS.chooseField),
    importColumnAs: (header: string) => t(WORDS.importColumnAs, { header }),
    leftOutHelper: t(WORDS.leftOutHelper),
    leaveColumnOut: t(WORDS.leaveColumnOut),
    fields: catalogImportFields(t),
    matching: t(WORDS.matching),
    heading: (rows: number) => t(WORDS.heading, { rows }),
    readyShort: (ready: number) => t(WORDS.readyShort, { ready }),
    readyLong: (ready: number, needYou: number) => t(WORDS.readyLong, { ready, needYou }),
    written: (applied: number, created: number) => t(WORDS.written, { applied, created }),
    willDo: t(WORDS.willDo),
    didDo: t(WORDS.didDo),
    barSentence: (parts: readonly { readonly label: string; readonly count: number }[]) =>
      assembled(parts.map((part) => t(WORDS.barPart, part)).join(', ')),
    ringLabel: (label: string, count: number) => t(WORDS.ringLabel, { label, count }),
    groups: map(Object.keys(GROUP) as (keyof typeof GROUP)[], (group) => t(GROUP[group])),
    groupTitle: (group: string, count: number) => t(WORDS.groupTitle, { group, count }),
    countRows: (count: number) => t(WORDS.countRows, { count }),
    overrideLine: t(WORDS.overrideLine),
    find: t(WORDS.find),
    matchLine: (found: number, rows: number, query: string) =>
      t(WORDS.matchLine, { found, rows, query }),
    needYou: t(WORDS.needYou),
    readyToImport: t(WORDS.readyToImport),
    fixedProgress: (fixed: number, of: number) => t(WORDS.fixedProgress, { fixed, of }),
    yourPrice: t(WORDS.yourPrice),
    setPrice: t(WORDS.setPrice),
    leaveOut: t(WORDS.leaveOut),
    keepSpec: t(WORDS.keepSpec),
    importAsOwn: t(WORDS.importAsOwn),
    useThisPrice: t(WORDS.useThisPrice),
    whichProduct: t(WORDS.whichProduct),
    chooseProduct: t(WORDS.chooseProduct),
    kindLabel: t(WORDS.kindLabel),
    chooseKind: t(WORDS.chooseKind),
    kinds: map(COMPONENT_KINDS, (kind: ComponentKind) => catalogKind(t, kind)),
    undo: t(WORDS.undo),
    outcomes: map(Object.keys(OUTCOME) as (keyof typeof OUTCOME)[], (key) => t(OUTCOME[key])),
    noPrice: t(WORDS.noPrice),
    unchanged: t(WORDS.unchanged),
    becomes: t(WORDS.becomes),
    importRows: (count: number) => t(WORDS.importRows, { count }),
    undoLine: t(WORDS.undoLine),
    nextColumns: t(WORDS.nextColumns),
    nextRows: t(WORDS.nextRows),
    continue: t(WORDS.continue),
    gates: map(Object.keys(GATE) as (keyof typeof GATE)[], (gate) => t(GATE[gate])),
    importing: t(WORDS.importing),
    ofRows: (total: number) => t(WORDS.ofRows, { total }),
    stopWatching: t(WORDS.stopWatching),
    keepsRunning: t(WORDS.keepsRunning),
    fixRows: (count: number) => t(WORDS.fixRows, { count }),
    kept: t(WORDS.kept),
    opening: t(WORDS.opening),
  };
}
